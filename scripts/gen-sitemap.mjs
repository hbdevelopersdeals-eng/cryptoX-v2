#!/usr/bin/env node
/* Sitemap generator — derived from src/lib/routes.js, never hand-edited.
 *
 *   node scripts/gen-sitemap.mjs          write public/sitemap.xml
 *   node scripts/gen-sitemap.mjs --check  fail if the committed file is stale
 *
 * Why a generator: a hand-written sitemap is the single most common lie a site
 * tells a crawler. It keeps listing routes after they are gated, renamed or
 * deleted, and every one of those entries becomes a coverage error. The
 * manifest in routes.js is already the source of truth for canonical tags, so
 * deriving the sitemap from the same list makes drift impossible.
 *
 * Deliberately no <lastmod>: we do not track per-page edit dates, and a made-up
 * date teaches Google to distrust the whole file. <priority> and <changefreq>
 * are emitted because some non-Google crawlers still read them.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SITE_URL } from '../src/lib/seo.js';
import { sitemapEntries } from '../src/lib/routes.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'sitemap.xml');
const CHECK = process.argv.includes('--check');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const base = SITE_URL.replace(/\/+$/, '');

const urls = sitemapEntries()
  .map((r) => {
    const loc = `${base}${r.path}`;
    return [
      '  <url>',
      `    <loc>${esc(loc)}</loc>`,
      `    <changefreq>${r.changefreq}</changefreq>`,
      `    <priority>${r.priority.toFixed(1)}</priority>`,
      '  </url>'
    ].join('\n');
  })
  .join('\n');

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/gen-sitemap.mjs from src/lib/routes.js. Do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== xml) {
    console.error('public/sitemap.xml is out of date. Run: npm run seo:sitemap');
    process.exit(1);
  }
  console.log(`Sitemap check: ${sitemapEntries().length} URL(s), in sync with routes.js.`);
} else {
  writeFileSync(OUT, xml, 'utf8');
  console.log(`Wrote public/sitemap.xml — ${sitemapEntries().length} indexable URL(s) under ${base}`);
}
